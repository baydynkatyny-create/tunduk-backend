function identifyUser(req, res, next) {
  let userId = req.cookies?.tunduk_uid;
  if (!userId) {
    userId = crypto.randomUUID();
    res.cookie("tunduk_uid", userId, {
      httpOnly: true,
      maxAge: 400 * 24 * 60 * 60 * 1000,
      sameSite: "lax",
    });
  }
  req.userId = userId;
  next();
}

