// Куплеттерди Suno тааныган структура-белгилери менен даярдайт:
// [Intro], [Verse N], ар бир куплеттен кийин [Instrumental Break],
// кайталанган куплетти [Chorus] деп белгилейт, аягында [Outro].
// Ушул структура — чыныгы ырлардагыдай, куплет бүткөндө музыкалык
// үзгүлтүк (брейк) болушун камсыз кылат.
function formatLyricsForSuno(text) {
  const stanzas = text
    .split(/\r?\n\s*\r?\n/)
    .map((s) => s.trim())
    .filter(Boolean);

  if (stanzas.length === 0) return text;
  if (stanzas.length === 1) {
    return `[Intro]\n\n[Verse 1]\n${stanzas[0]}\n\n[Outro]`;
  }

  // Кайталанган (мис. кайырма) куплетти таап, "Chorus" деп белгилейбиз
  const seen = new Map();
  stanzas.forEach((s, i) => {
    const norm = s.toLowerCase().replace(/\s+/g, " ");
    if (!seen.has(norm)) seen.set(norm, []);
    seen.get(norm).push(i);
  });
  const chorusIndexes = new Set();
  for (const idxs of seen.values()) {
    if (idxs.length > 1) idxs.forEach((i) => chorusIndexes.add(i));
  }

  const parts = ["[Intro]"];
  let verseNum = 0;
  stanzas.forEach((stanza, i) => {
    if (i > 0) parts.push("[Instrumental Break]"); // ар бир куплет бүткөндө музыкалык үзгүлтүк
    if (chorusIndexes.has(i)) {
      parts.push(`[Chorus]\n${stanza}`);
    } else {
      verseNum += 1;
      parts.push(`[Verse ${verseNum}]\n${stanza}`);
    }
  });
  parts.push("[Instrumental Break]", "[Outro]");
  return parts.join("\n\n");
}

