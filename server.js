// --- Текст ыр же жомок түрүндөбү, же жөнөкөй сүйлөмбү — ошону аныктайбыз ---
// Кийин ушул аныктоого жараша TTS'ке кандай "окуу стилинде" айт деген
// көрсөтмө кошуларын чечебиз.
function detectSpeechStyle(text) {
  const t = text.trim();
  const lines = t.split(/\r?\n/).filter((l) => l.trim().length > 0);

  // Жомокко мүнөздүү сөз-сайлар — башталышы, өтмө сөздөрү, аягы
  const taleMarkers = [
    "илгери илгери", "илгеркиде", "байыртан", "бир бар эле",
    "бир жолу", "аягы", "ошентип", "жомокчу", "жомок",
    "экен", "дешет", "уламыш",
  ];
  const lowerT = t.toLowerCase();
  const taleScore = taleMarkers.reduce(
    (acc, m) => acc + (lowerT.includes(m) ? 1 : 0),
    0
  );

  // Ыр көбүнчө көп сапка бөлүнөт, ар бир сап кыска келет
  const isLineBroken = lines.length >= 4;
  const avgLineLen = isLineBroken ? t.length / lines.length : Infinity;
  const looksLikePoem = isLineBroken && avgLineLen <= 70;

  if (taleScore >= 2) return "tale";
  if (looksLikePoem) return "poem";
  if (taleScore >= 1) return "tale";
  return "normal";
}

// Ырды сап-сап окуганда табигый пауза, интонация болушу үчүн,
// ар бир сапты өзүнчө "дем алуу" белгиси менен бөлүп беребиз.
// Gemini TTS насаат-инструкциядан көрө, тексттеги пунктуацияга көбүрөөк ылайыкташат.
function formatPoemForSpeech(text) {
  const lines = text.split(/\r?\n/);
  return lines
    .map((line) => {
      const trimmed = line.trim();
      if (!trimmed) return ""; // куплеттер арасындагы бош сап — узунураак пауза
      // Сап аягында пунктуация жок болсо, кичине пауза үчүн үтүр кошобуз
      if (/[.,!?…:;]$/.test(trimmed)) return trimmed;
      return trimmed + ",";
    })
    .join("\n");
}

