// Бардык образдардын алдына коюлуучу тил боюнча катуу эскертүү.
// Gemini'дин даяр добуштары (Kore, Orus, ж.б.) негизинен орус/англис
// тилине көбүрөөк көнүктүрүлгөндүктөн, кыргызча сүйлөгөндө орусча же
// англисче акцент/уруу аралашып кетиши мүмкүн. Ушул эскертүү аны азайтууга
// аракет кылат.
const KYRGYZ_LANGUAGE_GUARD =
  "[ТИЛ БОЮНЧА КАТУУ ЭРЕЖЕ]\n" +
  "Бул текст — ТАЗА КЫРГЫЗ ТИЛИНДЕ (kg-KG). Кыргызча эмес тилдин " +
  "(орусча, англисче, казакча ж.б.) уруусун, акцентин же интонациясын " +
  "ТАКЫР кошпо. Кыргыз тилине мүнөздүү тыбыштарды (ө, ү, ң, ы) так жана " +
  "нукура кыргызча айт — аларды орусча \"о\", \"у\", \"н\", \"и\" сыяктуу " +
  "айтпа. Сөздөрдү кыргыз тилинин өз айтылыш эрежесине ылайык, шашылбай, " +
  "даана муундап оку. Тексттеги ар бир сөз — кыргызча сөз, аны башка " +
  "тилдин сөзүнө окшотуп бурмалоо жол берилбейт.\n\n";

function buildSpeechInput(text, style, voiceKey) {
  if (!style) style = detectSpeechStyle(text);
  if (style === "poem") {
    const persona =
      POEM_VOICES[voiceKey] || POEM_VOICES[DEFAULT_POEM_VOICE];
    // "Эркин окурман" сыяктуу добуштар сап сайын механикалык токтоону
    // каалабайт — андай учурда сап аягына үтүр кошпой, чийки текстти беребиз.
    const formatted = persona.freeFlow ? text : formatPoemForSpeech(text);
    return (
      KYRGYZ_LANGUAGE_GUARD + persona.instruction + "\n\n" + formatted
    );
  }
  if (style === "tale") {
    return (
      KYRGYZ_LANGUAGE_GUARD +
      "Балага жомок айтып берген жомокчу сыяктуу, жай, жылуу, окуяны " +
      "сүрөттөп, интонацияны түрдүү каармандарга жараша өзгөртүп айтып бер:\n\n" +
      text
    );
  }
  return KYRGYZ_LANGUAGE_GUARD + text;
}

