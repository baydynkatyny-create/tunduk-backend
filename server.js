// Ар бир бөлүк сап чегинде бузулат (сөз ортосунан эмес), ошондуктан
// ыр саптары бузулбайт. Gemini TTS'тин бир чакырууда иштей ала турган
// текст өлчөмү чектелүү болгондуктан, бул узун ырларды/жоопторду
// бир нече чакыруу менен толук окутууга мүмкүндүк берет.
function splitTextForTTS(text, maxChars = 1800) {
  const lines = text.split(/\r?\n/);
  const chunks = [];
  let current = "";

  for (const line of lines) {
    const candidate = current ? current + "\n" + line : line;
    if (candidate.length > maxChars && current) {
      chunks.push(current);
      current = line;
    } else {
      current = candidate;
    }
  }
  if (current) chunks.push(current);
  return chunks.length > 0 ? chunks : [text];
}

// --- Бир нече PCM аудио бөлүктөрүн бир бүтүн аудиого бириктирүү ---
function concatPcmBase64(base64Parts) {
  const buffers = base64Parts.map((b64) => Buffer.from(b64, "base64"));
  return Buffer.concat(buffers).toString("base64");
}

// --- Текстти (керек болсо бир нече чакыруу менен) толук үнгө айландыруу ---
async function synthesizeFullSpeech(text, voiceKey) {
  const style = detectSpeechStyle(text);
  const chunks = splitTextForTTS(text);

  // Колдонуучу тандаган добушту стилге карабай ар дайым колдонобуз —
  // мурда "ыр" деп таанылбаган учурда добуш тандоо таштала турган.
  const voiceName = (POEM_VOICES[voiceKey] || POEM_VOICES[DEFAULT_POEM_VOICE]).voiceName;

  // Бөлүктөрдү КЕЗЕК-КЕЗЕК эмес, ПАРАЛЛЕЛЬ иштетебиз — узун
  // жомок/ырларда күтүү убактысын бир нече эсе кыскартат.
  const audioParts = await Promise.all(
    chunks.map(async (chunk) => {
      const speechInput = buildSpeechInput(chunk, style, voiceKey);
      const data = await geminiFetch("gemini-3.1-flash-tts-preview", {
        contents: [{ parts: [{ text: speechInput }] }],
        generationConfig: {
          responseModalities: ["AUDIO"],
          speechConfig: {
            voiceConfig: { prebuiltVoiceConfig: { voiceName } },
          },
        },
      });

      const part = data.candidates?.[0]?.content?.parts?.find((p) => p.inlineData);
      if (!part) {
        throw new Error("Үн кайтарылган жок (бир бөлүктө)");
      }
      return part.inlineData.data;
    })
  );

  return chunks.length === 1 ? audioParts[0] : concatPcmBase64(audioParts);
}

// --- Үн (текст → сүйлөө) эндпоинти ---
app.post("/api/speak", async (req, res) => {
  try {
    const { text, voiceKey } = req.body;
    if (!text || typeof text !== "string" || !text.trim()) {
      return res.status(400).json({ error: "text талаасы керек" });
    }

    const check = checkAndIncrement(req.userId, "chat");
    if (!check.allowed) {
      return res.status(429).json({
        error: `Күндүк чегиңизге жеттиңиз (${check.limit}). Планыңызды жогорулатсаңыз болот.`,
        usage: check,
      });
    }

    let audioBase64;
    try {
      audioBase64 = await synthesizeFullSpeech(text, voiceKey);
    } catch (e) {
      console.error("Gemini TTS error:", e.message);
      return res.status(502).json({ error: "Үн кызматы жооп берген жок" });
    }

    res.json({ audioBase64, usage: check });
  } catch (err) {
    console.error(err);
    res.status(500).json({ error: "Сервердик ката" });
  }
});

