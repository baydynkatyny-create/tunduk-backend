// Эскертүү: Gemini'дин сүрөт-генерация модели (gemini-3.1-flash-image) акысыз тарифте
// жок болгондуктан (ал акы төлөнүүчү гана), сахна сүрөттөрүн Pollinations.ai'дан алабыз.
async function generateImageDataUrl(prompt) {
  const encodedPrompt = encodeURIComponent(prompt);
  const seed = Math.floor(Math.random() * 1_000_000);
  const url = `https://image.pollinations.ai/prompt/${encodedPrompt}?width=768&height=1344&nologo=true&seed=${seed}`;

  const response = await fetch(url);
  if (!response.ok) {
    throw new Error("Pollinations катасы: " + response.status);
  }

  const arrayBuffer = await response.arrayBuffer();
  const base64 = Buffer.from(arrayBuffer).toString("base64");
  const contentType = response.headers.get("content-type") || "image/jpeg";
  return `data:${contentType};base64,${base64}`;
}

