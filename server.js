// Сапат чектелген: 2-4 секунддук, төмөн резолюциядагы клиптер (акысыз моделдин чеги).
// Hugging Face ачкычтары: биринчиси лимитке (rate limit) жетсе, автоматтык
// түрдө кийинкисине которулуу үчүн. .env файлында HF_API_KEY (милдеттүү),
// HF_API_KEY_2ден HF_API_KEY_10го чейин (каалосу боюнча) кошсоңуз болот.
const HF_API_KEYS = [
  process.env.HF_API_KEY,
  process.env.HF_API_KEY_2,
  process.env.HF_API_KEY_3,
  process.env.HF_API_KEY_4,
  process.env.HF_API_KEY_5,
].filter(Boolean);
let activeHfKeyIndex = 0;
console.log(`Hugging Face ачкычтары жүктөлдү: ${HF_API_KEYS.length} даана`);

async function generateVideoClip(prompt) {
  if (HF_API_KEYS.length === 0) {
    throw new Error("HF_API_KEY коюлган эмес — акысыз видео-генерация иштебейт");
  }

  const model = process.env.HF_VIDEO_MODEL || "damo-vilab/text-to-video-ms-1.7b";

  let lastError;
  for (let attempt = 0; attempt < HF_API_KEYS.length; attempt++) {
    const key = HF_API_KEYS[activeHfKeyIndex];
    const response = await fetch(`https://api-inference.huggingface.co/models/${model}`, {
      method: "POST",
      headers: {
        Authorization: `Bearer ${key}`,
        "Content-Type": "application/json",
      },
      body: JSON.stringify({ inputs: prompt }),
    });

    if (response.ok) {
      const contentType = response.headers.get("content-type") || "video/mp4";
      const arrayBuffer = await response.arrayBuffer();
      const base64 = Buffer.from(arrayBuffer).toString("base64");
      return `data:${contentType};base64,${base64}`;
    }

    const status = response.status;
    const errText = await response.text();
    lastError = new Error(`Hugging Face видео катасы (${status}): ${errText}`);

    // 429 (rate limit) же 402/403 (квота/уруксат) — ачкычты алмаштырабыз
    if ((status === 429 || status === 402 || status === 403) && HF_API_KEYS.length > 1) {
      const nextIndex = (activeHfKeyIndex + 1) % HF_API_KEYS.length;
      console.warn(
        `HF ачкыч #${activeHfKeyIndex + 1} лимитке жетти (${status}). Ачкыч #${nextIndex + 1}гө которулду.`
      );
      activeHfKeyIndex = nextIndex;
      continue;
    }

    throw lastError;
  }

  throw lastError || new Error("Бардык Hugging Face ачкычтары лимитке жетти");
}

